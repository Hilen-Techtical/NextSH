    @Test
    fun `a forged length is refused without allocating it`() {
        val magic = "openssh-key-v1".toByteArray(Charsets.US_ASCII) + byteArrayOf(0)
        val head = magic + str("none") + str("none") + str(ByteArray(0)) + u32(1)
        fun file(body: ByteArray) = armor("OPENSSH PRIVATE KEY", body, lineLength = 70)

        // Ed25519 envelope announcing a 2 GiB key (SSHJ allocates it and throws an OutOfMemoryError).
        val hugeKey = str("ssh-ed25519") + u32(0x7FFFFFFF)
        assertEquals(SshPublicKeyDerivation.Unreadable, derive(file(head + str(hugeKey) + str(ByteArray(8)))))
        // The envelope string itself announcing 2 GiB.
        assertEquals(SshPublicKeyDerivation.Unreadable, derive(file(head + u32(0x7FFFFFFF) + ByteArray(16))))
        // A sane envelope, then a private section whose public copy announces 2 GiB.
        val pair = TestKeyFiles.ed25519()
        val section = u32(1) + u32(1) + str("ssh-ed25519") + u32(0x7FFFFFFF) + ByteArray(13)
        assertEquals(0, section.size % 8) // reaches the field, not the block size check
        assertEquals(SshPublicKeyDerivation.Unreadable, derive(file(head + str(blobOf(pair.public)) + str(section))))
        // An ECDSA point and an RSA mpint announcing 2 GiB.
        assertEquals(SshPublicKeyDerivation.Unreadable, derive(file(head + str(str("ecdsa-sha2-nistp256") + str("nistp256") + u32(0x7FFFFFFF)) + str(ByteArray(8)))))
        assertEquals(SshPublicKeyDerivation.Unreadable, derive(file(head + str(str("ssh-rsa") + u32(0x7FFFFFFF)) + str(ByteArray(8)))))
        // Many keys announced.
        val many = magic + str("none") + str("none") + str(ByteArray(0)) + u32(0x7FFFFFFF)
        assertEquals(SshPublicKeyDerivation.Unreadable, derive(file(many + str(blobOf(pair.public)) + str(ByteArray(8)))))
    }

    @Test
    fun `a corrupted clear key is unreadable`() {
        val pair = TestKeyFiles.ed25519()
        val fields = TestKeyFiles.opensshPrivateFields(pair)
        assertEquals(SshPublicKeyDerivation.Unreadable, derive(TestKeyFiles.openssh(fields, blobOf(pair.public), checkInts = 1L to 2L)))
        assertEquals(SshPublicKeyDerivation.Unreadable, derive("-----BEGIN OPENSSH PRIVATE KEY-----\nnot base64!\n-----END OPENSSH PRIVATE KEY-----\n"))
        assertEquals(SshPublicKeyDerivation.Unreadable, derive("-----BEGIN OPENSSH PRIVATE KEY-----\nAAAA\n"))
        assertEquals(SshPublicKeyDerivation.Unreadable, derive("-----BEGIN PRIVATE KEY-----\nAAAA\n-----END PRIVATE KEY-----\n"))
        assertEquals(SshPublicKeyDerivation.Unreadable, derive(""))
        assertEquals(SshPublicKeyDerivation.Unreadable, derive("FIXTURE-NOT-A-REAL-PRIVATE-KEY"))
    }

    @Test
    fun `an RSA key whose private part belongs to another key fails its proof`() {
        val a = TestKeyFiles.rsa().private as RSAPrivateCrtKey
        val b = TestKeyFiles.rsa().private as RSAPrivateCrtKey
        val mixed = Buffer.PlainBuffer().putString("ssh-rsa")
            .putMPInt(a.modulus).putMPInt(a.publicExponent).putMPInt(b.privateExponent)
            .putMPInt(b.crtCoefficient).putMPInt(b.primeP).putMPInt(b.primeQ).compactData
        val envelope = Buffer.PlainBuffer().putString("ssh-rsa").putMPInt(a.publicExponent).putMPInt(a.modulus).compactData
        assertEquals(SshPublicKeyDerivation.Unreadable, derive(TestKeyFiles.openssh(mixed, envelope)))
    }

    @Test
    fun `random content never throws and is never derived`() {
        val random = Random(20261118)
        repeat(300) {
            val body = random.nextBytes(random.nextInt(0, 600))
            val result = derive(armor("OPENSSH PRIVATE KEY", body, lineLength = 70))
            assertTrue(result !is SshPublicKeyDerivation.Derived && result !is SshPublicKeyDerivation.Inconsistent)
            val pkcs = derive(armor("PRIVATE KEY", body))
            assertTrue(pkcs !is SshPublicKeyDerivation.Derived)
        }
    }

    @Test
    fun `a result never prints key material`() {
        val pair = TestKeyFiles.ed25519()
        val derived = derive(TestKeyFiles.openssh(pair))
        assertEquals("Derived", derived.toString())
        val blob = blobBase64Of(pair.public)
        assertTrue(!derived.toString().contains(blob))
    }
