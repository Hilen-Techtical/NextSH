    @Test
    fun `PKCS1 RSA and SEC1 EC keys are derived, an embedded public key of a third party is inconsistent`() {
        val rsa = TestKeyFiles.rsa()
        assertDerived(rsa.public, SshKeyType.RSA_4096, derive(armor("RSA PRIVATE KEY", TestKeyFiles.pkcs1Der(rsa.private as RSAPrivateCrtKey))))

        val ec = TestKeyFiles.ec(EcCurve.P384)
        val key = ec.private as ECPrivateKey
        val own = TestKeyFiles.pointOf(ec.public as ECPublicKey)
        val other = TestKeyFiles.pointOf(TestKeyFiles.ec(EcCurve.P384).public as ECPublicKey)
        for (embedded in listOf(null, own)) {
            val pem = armor("EC PRIVATE KEY", TestKeyFiles.sec1Der(key, EcCurve.P384, embedded))
            assertDerived(ec.public, SshKeyType.ECDSA_384, derive(pem))
        }
        // SSHJ presents the embedded public key at connection: one of a third party makes the file inconsistent,
        // and the real key is still given.
        val forged = derive(armor("EC PRIVATE KEY", TestKeyFiles.sec1Der(key, EcCurve.P384, other)))
        assertDerived(ec.public, SshKeyType.ECDSA_384, assertIs<SshPublicKeyDerivation.Inconsistent>(forged).derived)
        // A PKCS#8 EC key is read by SSHJ with Q recomputed: nothing embedded to compare.
        assertDerived(ec.public, SshKeyType.ECDSA_384, derive(TestKeyFiles.pkcs8(ec)))
    }

    @Test
    fun `a forged RSA key with full size primes is refused before any signature`() {
        val rnd = java.security.SecureRandom()
        fun big(bits: Int): BigInteger = BigInteger(bits, rnd).setBit(bits - 1).setBit(0)
        val n = big(SshPublicKeyDeriver.MAX_RSA_BITS)
        val p = big(SshPublicKeyDeriver.MAX_RSA_BITS)
        val q = big(SshPublicKeyDeriver.MAX_RSA_BITS)
        val e = BigInteger.valueOf(65537)
        val d = big(SshPublicKeyDeriver.MAX_RSA_BITS - 1)
        val dP = big(16_000)
        val dQ = big(16_000)
        val qInv = big(16_000)

        val fields = Buffer.PlainBuffer().putString("ssh-rsa")
            .putMPInt(n).putMPInt(e).putMPInt(d).putMPInt(qInv).putMPInt(p).putMPInt(q).compactData
        val envelope = Buffer.PlainBuffer().putString("ssh-rsa").putMPInt(e).putMPInt(n).compactData
        val openssh = TestKeyFiles.openssh(fields, envelope)
        val pkcs1 = armor(
            "RSA PRIVATE KEY",
            TestKeyFiles.seq(
                TestKeyFiles.int(BigInteger.ZERO), TestKeyFiles.int(n), TestKeyFiles.int(e), TestKeyFiles.int(d),
                TestKeyFiles.int(p), TestKeyFiles.int(q), TestKeyFiles.int(dP), TestKeyFiles.int(dQ), TestKeyFiles.int(qInv),
            ),
        )
        for (pem in listOf(openssh, pkcs1)) {
            // The budget counts every signature: two CRT exponentiations of 16 384 bits are never attempted.
            val budget = ProofBudget()
            assertEquals(SshPublicKeyDerivation.Unreadable, SshPublicKeyDeriver.derive(pem, null, budget))
            assertEquals(0, budget.signatures)
        }
        val material = PrivateKeyMaterial.Rsa(n, e, d, p, q, dP, dQ, qInv)
        assertFalse(with(SshPublicKeyDeriver) { material.isWellFormed() })

        // Each CRT value at or over its prime is refused too, on a real key.
        val real = TestKeyFiles.rsa().private as RSAPrivateCrtKey
        fun crt(dP: BigInteger = real.primeExponentP, dQ: BigInteger = real.primeExponentQ, qInv: BigInteger = real.crtCoefficient) =
            PrivateKeyMaterial.Rsa(real.modulus, real.publicExponent, real.privateExponent, real.primeP, real.primeQ, dP, dQ, qInv)
        assertTrue(with(SshPublicKeyDeriver) { crt().isWellFormed() })
        assertFalse(with(SshPublicKeyDeriver) { crt(dP = real.primeP).isWellFormed() })
        assertFalse(with(SshPublicKeyDeriver) { crt(dQ = real.primeQ.add(BigInteger.ONE)).isWellFormed() })
        assertFalse(with(SshPublicKeyDeriver) { crt(qInv = real.primeP).isWellFormed() })
    }

    @Test
    fun `an RSA key with unbalanced primes is refused before any signature`() {
        // q = 3 next to a p of 16 382 bits: p q = n holds, the CRT values are below their primes, and the
        // exponentiation modulo p would cost about four times a real 16 384 bit key.
        val rnd = java.security.SecureRandom()
        fun big(bits: Int): BigInteger = BigInteger(bits, rnd).setBit(bits - 1).setBit(0)
        val p = big(SshPublicKeyDeriver.MAX_RSA_BITS - 2)
        val q = BigInteger.valueOf(3)
        val n = p.multiply(q)
        val e = BigInteger.valueOf(65537)
        val d = big(SshPublicKeyDeriver.MAX_RSA_BITS - 4)
        val dP = big(16_000)
        val material = PrivateKeyMaterial.Rsa(n, e, d, p, q, dP, BigInteger.ONE, BigInteger.ONE)
        assertTrue(n.bitLength() <= SshPublicKeyDeriver.MAX_RSA_BITS)
        assertFalse(with(SshPublicKeyDeriver) { material.isWellFormed() })

        val fields = Buffer.PlainBuffer().putString("ssh-rsa")
            .putMPInt(n).putMPInt(e).putMPInt(d).putMPInt(BigInteger.ONE).putMPInt(p).putMPInt(q).compactData
        val envelope = Buffer.PlainBuffer().putString("ssh-rsa").putMPInt(e).putMPInt(n).compactData
        val budget = ProofBudget()
        assertEquals(SshPublicKeyDerivation.Unreadable, SshPublicKeyDeriver.derive(TestKeyFiles.openssh(fields, envelope), null, budget))
        assertEquals(0, budget.signatures)

        // Primes of real keys are 16 bits apart at most; the generated ones are balanced and accepted.
        val real = TestKeyFiles.rsa().private as RSAPrivateCrtKey
        assertTrue(kotlin.math.abs(real.primeP.bitLength() - real.primeQ.bitLength()) <= 16)
    }

