    @Test
    fun `the iteration count of an encrypted PKCS8 key is bounded before any list of accepted algorithms`() {
        val rsa = TestKeyFiles.rsa()
        val huge = Int.MAX_VALUE // 2^31 - 1: BouncyCastle would run them all, whatever the PRF or the scheme
        // A PRF BouncyCastle knows (HMAC SHA3-256) but this deriver does not take, and a scheme it does not take.
        for (pem in listOf(
            TestKeyFiles.encryptedPkcs8(rsa.private.encoded, "p".toCharArray(), iterations = 1, declaredIterations = huge, prf = TestKeyFiles.HMAC_SHA3_256_OID),
            TestKeyFiles.encryptedPkcs8(rsa.private.encoded, "p".toCharArray(), iterations = 1, declaredIterations = huge, scheme = TestKeyFiles.AES256_GCM_OID),
        )) {
            assertEquals(SshPublicKeyDerivation.TooCostly, derive(pem, "p"))
            assertEquals(SshPublicKeyDerivation.TooCostly, derive(pem, null))
        }

        // PBES1 and PKCS#12 schemes: never accepted, but over the bound they are too costly first.
        for (scheme in listOf(TestKeyFiles.PBE_MD5_DES_OID, TestKeyFiles.PBE_SHA_3DES_PKCS12_OID)) {
            val costly = TestKeyFiles.encryptedPkcs8Legacy(scheme, BigInteger.valueOf(huge.toLong()))
            assertEquals(SshPublicKeyDerivation.TooCostly, derive(costly, "p"))
            assertEquals(SshPublicKeyDerivation.TooCostly, derive(costly, null))
            val cheap = TestKeyFiles.encryptedPkcs8Legacy(scheme, BigInteger.valueOf(2048))
            assertEquals(SshPublicKeyDerivation.UnsupportedEncryption, derive(cheap, "p"))
            assertEquals(SshPublicKeyDerivation.UnsupportedEncryption, derive(cheap, null))
        }
        // An unknown scheme with no readable count: unsupported, never handed to another reader.
        assertEquals(
            SshPublicKeyDerivation.UnsupportedEncryption,
            derive(TestKeyFiles.encryptedPkcs8Legacy(TestKeyFiles.AES256_GCM_OID, BigInteger.valueOf(huge.toLong())), "p"),
        )
    }

    // ---- AEAD OpenSSH keys written by ssh-keygen 9.5 ----

    /**
     * Throwaway test keys written by ssh-keygen 9.5 (`-a 16`, comment `t`, passphrase `pass-x`), kept in
     * `src/desktopTest/resources/ssh-keys/`. They protect nothing and must never be used anywhere else.
     */
    private fun resource(name: String): String =
        SshPublicKeyDeriverTest::class.java.getResource("/ssh-keys/$name")?.readText() ?: fail("missing test key $name")

    /** [pem] with the last byte of its content flipped: the AEAD tag of an encrypted OpenSSH key. */
    private fun tamperLastByte(pem: String): String {
        val lines = pem.trim().lines().map { it.trim() }
        val body = Base64.getDecoder().decode(lines.drop(1).dropLast(1).joinToString(""))
        body[body.size - 1] = (body[body.size - 1].toInt() xor 1).toByte()
        return armor("OPENSSH PRIVATE KEY", body, lineLength = 70)
    }

    private fun assertAeadKey(name: String) {
        val pem = resource(name)
        val expected = SshPublicKeyLine.blobKey(resource("$name.pub"))
        val derived = assertIs<SshPublicKeyDerivation.Derived>(derive(pem, "pass-x"), name)
        assertEquals(expected, derived.blobKey, name)
        assertEquals(SshKeyType.ED25519, derived.keyType)
        assertEquals(SshPublicKeyDerivation.WrongPassphrase, derive(pem, "pass-y"), name)
        assertEquals(SshPublicKeyDerivation.NeedsPassphrase, derive(pem, null), name)
        assertEquals(SshPublicKeyDerivation.WrongPassphrase, derive(tamperLastByte(pem), "pass-x"), "$name with a tampered tag")
    }

