/**
 * [SshPublicKeyDeriver] on keys generated by the JDK at run time (no key material in the sources). The
 * expected public key always comes from another code path ([KnownHostPortable] or SSHJ).
 */
class SshPublicKeyDeriverTest {

    private fun derive(pem: String, passphrase: String? = null): SshPublicKeyDerivation =
        SshPublicKeyDeriver.derive(pem, passphrase?.toCharArray())

    private fun assertDerived(expected: java.security.PublicKey, keyType: SshKeyType, result: SshPublicKeyDerivation) {
        val derived = assertIs<SshPublicKeyDerivation.Derived>(result)
        assertEquals(blobBase64Of(expected), derived.blobBase64)
        assertEquals(keyType, derived.keyType)
        assertEquals(Buffer.PlainBuffer(blobOf(expected)).readString(), derived.sshType)
    }

    /** SSHJ reads [pem] and its public key equals [expectedBase64] (checks the test writer against SSHJ). */
    private fun assertSshjReads(pem: String, expectedBase64: String, passphrase: String? = null) {
        SecurityUtils.isBouncyCastleRegistered() // the ECDSA reader of SSHJ asks the provider for "ECDSA"
        val file = OpenSSHKeyV1KeyFile()
        file.init(StringReader(pem), passphrase?.let { PasswordUtils.createOneOff(it.toCharArray()) })
        file.private // forces the read of the private part (SSHJ reads lazily)
        assertEquals(expectedBase64, Base64.getEncoder().encodeToString(Buffer.PlainBuffer().putPublicKey(file.public).compactData))
    }

    // ---- OpenSSH v1 ----

    @Test
    fun `an Ed25519 key written by the shared writer is derived and read by SSHJ`() {
        val pair = TestKeyFiles.ed25519()
        val pem = OpenSshPrivateKeyWriter.ed25519(TestKeyFiles.seedOf(pair), "laptop")
        assertDerived(pair.public, SshKeyType.ED25519, derive(pem))
        assertSshjReads(pem, blobBase64Of(pair.public))
        assertTrue(pem.startsWith("-----BEGIN OPENSSH PRIVATE KEY-----\n"))
    }

    @Test
    fun `OpenSSH v1 Ed25519, RSA and ECDSA keys are derived`() {
        val ed = TestKeyFiles.ed25519()
        assertDerived(ed.public, SshKeyType.ED25519, derive(TestKeyFiles.openssh(ed)))

        val rsa = TestKeyFiles.rsa()
        val rsaPem = TestKeyFiles.openssh(rsa)
        assertSshjReads(rsaPem, blobBase64Of(rsa.public))
        assertDerived(rsa.public, SshKeyType.RSA_4096, derive(rsaPem))

        for ((curve, type) in listOf(EcCurve.P256 to SshKeyType.ECDSA_256, EcCurve.P384 to SshKeyType.ECDSA_384, EcCurve.P521 to SshKeyType.ECDSA_521)) {
            val ec = TestKeyFiles.ec(curve)
            val pem = TestKeyFiles.openssh(ec, curve)
            assertSshjReads(pem, blobBase64Of(ec.public))
            assertDerived(ec.public, type, derive(pem))
        }
    }

    @Test
    fun `a file whose clear public key is a third party's is inconsistent and gives the real key`() {
        val ed = TestKeyFiles.ed25519()
        val edResult = derive(TestKeyFiles.openssh(TestKeyFiles.opensshPrivateFields(ed), blobOf(TestKeyFiles.ed25519().public)))
        assertDerived(ed.public, SshKeyType.ED25519, assertIs<SshPublicKeyDerivation.Inconsistent>(edResult).derived)

        val rsa = TestKeyFiles.rsa()
        val rsaResult = derive(TestKeyFiles.openssh(TestKeyFiles.opensshPrivateFields(rsa), blobOf(TestKeyFiles.rsa().public)))
        assertDerived(rsa.public, SshKeyType.RSA_4096, assertIs<SshPublicKeyDerivation.Inconsistent>(rsaResult).derived)

        val ec = TestKeyFiles.ec(EcCurve.P256)
        val ecResult = derive(TestKeyFiles.openssh(TestKeyFiles.opensshPrivateFields(ec, EcCurve.P256), blobOf(TestKeyFiles.ec(EcCurve.P256).public)))
        assertDerived(ec.public, SshKeyType.ECDSA_256, assertIs<SshPublicKeyDerivation.Inconsistent>(ecResult).derived)

        // Another type in the envelope is inconsistent too.
        val mixed = derive(TestKeyFiles.openssh(TestKeyFiles.opensshPrivateFields(ed), blobOf(rsa.public)))
        assertDerived(ed.public, SshKeyType.ED25519, assertIs<SshPublicKeyDerivation.Inconsistent>(mixed).derived)
    }

    @Test
    fun `an encrypted OpenSSH key needs its passphrase and opens with the right one only`() {
