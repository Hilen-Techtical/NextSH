    @Test
    fun `bcrypt rounds over the bound are refused without running the KDF`() {
        val fields = TestKeyFiles.opensshPrivateFields(TestKeyFiles.ed25519())
        val envelope = blobOf(TestKeyFiles.ed25519().public)
        // 2^31 - 1 rounds would never end: the test itself shows that the KDF is never run.
        for (rounds in listOf(SshPublicKeyDeriver.MAX_BCRYPT_ROUNDS + 1L, Int.MAX_VALUE.toLong(), 0xFFFFFFFFL)) {
            val pem = TestKeyFiles.openssh(fields, envelope, kdfRoundsField = rounds)
            assertEquals(SshPublicKeyDerivation.TooCostly, derive(pem, "any"), "$rounds rounds")
            assertEquals(SshPublicKeyDerivation.TooCostly, derive(pem, null), "$rounds rounds without passphrase")
        }
        val zero = TestKeyFiles.openssh(fields, envelope, kdfRoundsField = 0)
        assertEquals(SshPublicKeyDerivation.Unreadable, derive(zero, "any"))
    }

    @Test
    fun `an OpenSSH key with an unknown cipher or KDF is an unsupported encryption, its cost checked first`() {
        val pair = TestKeyFiles.ed25519()
        val fields = TestKeyFiles.opensshPrivateFields(pair)
        val envelope = blobOf(pair.public)

        val unknownCipher = TestKeyFiles.openssh(fields, envelope, kdfRoundsField = 16, cipherName = "rot13-cbc")
        assertEquals(SshPublicKeyDerivation.UnsupportedEncryption, derive(unknownCipher, "x"))
        assertEquals(SshPublicKeyDerivation.UnsupportedEncryption, derive(unknownCipher, null))
        val unknownKdf = TestKeyFiles.openssh(fields, envelope, kdfRoundsField = 16, kdfName = "argon2")
        assertEquals(SshPublicKeyDerivation.UnsupportedEncryption, derive(unknownKdf, "x"))

        // The rounds are bounded before the cipher list, and before the key type list.
        val costlyUnknownCipher = TestKeyFiles.openssh(fields, envelope, kdfRoundsField = Int.MAX_VALUE.toLong(), cipherName = "rot13-cbc")
        assertEquals(SshPublicKeyDerivation.TooCostly, derive(costlyUnknownCipher, "x"))
        assertEquals(SshPublicKeyDerivation.TooCostly, derive(costlyUnknownCipher, null))
        val sk = str("sk-ssh-ed25519@openssh.com") + str(ByteArray(32) { 3 }) + str("ssh:")
        assertEquals(SshPublicKeyDerivation.TooCostly, derive(TestKeyFiles.openssh(ByteArray(0), sk, kdfRoundsField = Int.MAX_VALUE.toLong())))
        assertEquals(SshPublicKeyDerivation.Unsupported, derive(TestKeyFiles.openssh(ByteArray(0), sk, kdfRoundsField = 16)))
    }

