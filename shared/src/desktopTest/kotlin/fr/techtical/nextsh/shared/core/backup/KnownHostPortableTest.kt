package fr.techtical.nextsh.shared.core.backup

import net.schmizz.sshj.common.Buffer
import java.security.KeyPairGenerator
import java.security.PublicKey
import java.security.spec.ECGenParameterSpec
import java.util.Base64
import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlin.test.assertEquals
import kotlin.test.assertNotNull
import kotlin.test.assertNull
import kotlin.test.assertTrue

class KnownHostPortableTest {

    private val ed25519Blob =
        "AAAAC3NzaC1lZDI1NTE5AAAAIEuIMek2W/uP4SbNqKjs93fVaAPm7ymy6RBjcJZssbhi"

    private fun fixtureKnownHosts(): List<BackupKnownHost> =
        BackupCodec.decode(BackupFixtures.read("v2-complet.json")).decodedOrFail().document.knownHosts

    /** The path SSHJ takes to read the server key during the handshake. */
    private fun handshakePath(blobBase64: String): PublicKey =
        Buffer.PlainBuffer(Base64.getDecoder().decode(blobBase64)).readPublicKey()

    @Test
    fun `the fixtures cover the five key types`() {
        assertEquals(
            setOf("ssh-ed25519", "ssh-rsa", "ecdsa-sha2-nistp256", "ecdsa-sha2-nistp384", "ecdsa-sha2-nistp521"),
            fixtureKnownHosts().map { it.keyType }.toSet(),
        )
    }

    @Test
    fun `import gives the same algorithm and encoding as the handshake path`() {
        for (k in fixtureKnownHosts()) {
            val local = assertNotNull(KnownHostPortable.fromPortable(k.keyType, k.publicKey), k.keyType)
            val expected = handshakePath(k.publicKey)
            assertEquals(expected.algorithm, local.algorithm, k.keyType)
            assertContentEquals(expected.encoded, local.encoded, k.keyType)
        }
    }

    @Test
    fun `local to portable to local is the identity for every key type`() {
        for (k in fixtureKnownHosts()) {
            val handshake = handshakePath(k.publicKey)

            // local -> portable: back to the very same SSH blob and type.
            val portable = assertNotNull(KnownHostPortable.toPortable(handshake.algorithm, handshake.encoded), k.keyType)
            assertEquals(k.keyType, portable.keyType)
            assertEquals(k.publicKey, portable.publicKey, k.keyType)

            // portable -> local: the same local pair again.
            val local = assertNotNull(KnownHostPortable.fromPortable(portable.keyType, portable.publicKey))
            assertEquals(KnownHostPortable.LocalKey(handshake.algorithm, handshake.encoded), local)
        }
    }

    @Test
    fun `keys generated by the JDK export to the expected type and read back`() {
        fun check(expectedType: String, key: PublicKey) {
            val portable = assertNotNull(KnownHostPortable.toPortable(key.algorithm, key.encoded), expectedType)
            assertEquals(expectedType, portable.keyType)
            val local = assertNotNull(KnownHostPortable.fromPortable(portable.keyType, portable.publicKey), expectedType)
            val handshake = handshakePath(portable.publicKey)
            assertEquals(handshake.algorithm, local.algorithm)
            assertContentEquals(handshake.encoded, local.encoded)
        }

        check("ssh-ed25519", KeyPairGenerator.getInstance("Ed25519").generateKeyPair().public)
        check("ssh-rsa", KeyPairGenerator.getInstance("RSA").apply { initialize(2048) }.generateKeyPair().public)
        for ((curve, type) in listOf(
            "secp256r1" to "ecdsa-sha2-nistp256",
            "secp384r1" to "ecdsa-sha2-nistp384",
            "secp521r1" to "ecdsa-sha2-nistp521",
        )) {
            val pair = KeyPairGenerator.getInstance("EC").apply { initialize(ECGenParameterSpec(curve)) }.generateKeyPair()
            check(type, pair.public)
        }
    }

    @Test
    fun `for RSA and EC the imported encoding equals the original X509`() {
        val rsa = KeyPairGenerator.getInstance("RSA").apply { initialize(2048) }.generateKeyPair().public
        val portable = assertNotNull(KnownHostPortable.toPortable(rsa.algorithm, rsa.encoded))
        val local = assertNotNull(KnownHostPortable.fromPortable(portable.keyType, portable.publicKey))
        assertContentEquals(rsa.encoded, local.encoded)
    }

    @Test
    fun `provider name variants of EC and Ed25519 are accepted`() {
        val ec = KeyPairGenerator.getInstance("EC").apply { initialize(ECGenParameterSpec("secp256r1")) }.generateKeyPair().public
        assertEquals("ecdsa-sha2-nistp256", KnownHostPortable.toPortable("ECDSA", ec.encoded)?.keyType)
        assertEquals("ecdsa-sha2-nistp256", KnownHostPortable.toPortable("EC", ec.encoded)?.keyType)

        val ed = KeyPairGenerator.getInstance("Ed25519").generateKeyPair().public
        assertEquals("ssh-ed25519", KnownHostPortable.toPortable("Ed25519", ed.encoded)?.keyType)
        assertEquals("ssh-ed25519", KnownHostPortable.toPortable("EdDSA", ed.encoded)?.keyType)
    }

    @Test
    fun `export returns null for unsupported or broken keys`() {
        val ed = KeyPairGenerator.getInstance("Ed25519").generateKeyPair().public.encoded
        assertNull(KnownHostPortable.toPortable("DSA", ed))
        assertNull(KnownHostPortable.toPortable("RSA", ed)) // not an RSA structure
        assertNull(KnownHostPortable.toPortable("EC", ed))
        assertNull(KnownHostPortable.toPortable("EdDSA", ed.copyOf(ed.size - 1)))
        assertNull(KnownHostPortable.toPortable("EdDSA", ByteArray(44)))
        assertNull(KnownHostPortable.toPortable("RSA", ByteArray(0)))
        assertNull(KnownHostPortable.toPortable("", ed))
    }

    @Test
    fun `import refuses a type outside the allow-list`() {
        assertNull(KnownHostPortable.fromPortable("ssh-dss", ed25519Blob))
        assertNull(KnownHostPortable.fromPortable("sk-ssh-ed25519@openssh.com", ed25519Blob))
        assertNull(KnownHostPortable.fromPortable("", ed25519Blob))
        assertNull(KnownHostPortable.fromPortable("SSH-ED25519", ed25519Blob))
    }

    @Test
    fun `import refuses a declared type different from the type in the blob`() {
        assertNull(KnownHostPortable.fromPortable("ssh-rsa", ed25519Blob))
        assertNull(KnownHostPortable.fromPortable("ecdsa-sha2-nistp256", ed25519Blob))
        val rsa = fixtureKnownHosts().first { it.keyType == "ssh-rsa" }
        assertNull(KnownHostPortable.fromPortable("ssh-ed25519", rsa.publicKey))
        val p384 = fixtureKnownHosts().first { it.keyType == "ecdsa-sha2-nistp384" }
        assertNull(KnownHostPortable.fromPortable("ecdsa-sha2-nistp256", p384.publicKey))
    }

    @Test
    fun `import refuses bad base64`() {
        assertNull(KnownHostPortable.fromPortable("ssh-ed25519", ""))
        assertNull(KnownHostPortable.fromPortable("ssh-ed25519", "not base64!"))
        assertNull(KnownHostPortable.fromPortable("ssh-ed25519", ed25519Blob.dropLast(1)))
        assertNull(KnownHostPortable.fromPortable("ssh-ed25519", " $ed25519Blob"))
        assertNull(KnownHostPortable.fromPortable("ssh-ed25519", "$ed25519Blob\n"))
    }

    @Test
    fun `import refuses garbage, truncated and padded blobs`() {
        val blob = Base64.getDecoder().decode(ed25519Blob)
        fun b64(bytes: ByteArray) = Base64.getEncoder().encodeToString(bytes)

        assertNull(KnownHostPortable.fromPortable("ssh-ed25519", b64(ByteArray(40) { 7 })))
        assertNull(KnownHostPortable.fromPortable("ssh-ed25519", b64(blob.copyOf(blob.size - 5))))
        assertNull(KnownHostPortable.fromPortable("ssh-ed25519", b64(blob + byteArrayOf(1)))) // trailing byte
        assertNull(KnownHostPortable.fromPortable("ssh-ed25519", b64(blob + blob))) // two keys
        assertNotNull(KnownHostPortable.fromPortable("ssh-ed25519", b64(blob)))
    }

    private fun u32(v: Int): ByteArray =
        byteArrayOf((v ushr 24).toByte(), (v ushr 16).toByte(), (v ushr 8).toByte(), v.toByte())

    private fun str(bytes: ByteArray): ByteArray = u32(bytes.size) + bytes

    private fun str(text: String): ByteArray = str(text.encodeToByteArray())

    private fun b64(bytes: ByteArray): String = Base64.getEncoder().encodeToString(bytes)

    @Test
    fun `a huge claimed length is refused without allocating (no OutOfMemoryError)`() {
        val huge = u32(0x7FFFFFFF)

        // 19 bytes: string "ssh-ed25519" then a 2 GiB length.
        val ed = str("ssh-ed25519") + huge
        assertEquals(19, ed.size)
        assertNull(KnownHostPortable.fromPortable("ssh-ed25519", b64(ed)))

        for ((type, curve) in listOf(
            "ecdsa-sha2-nistp256" to "nistp256",
            "ecdsa-sha2-nistp384" to "nistp384",
            "ecdsa-sha2-nistp521" to "nistp521",
        )) {
            assertNull(KnownHostPortable.fromPortable(type, b64(str(type) + str(curve) + huge)), type)
            assertNull(KnownHostPortable.fromPortable(type, b64(str(type) + huge)), type)
        }

        assertNull(KnownHostPortable.fromPortable("ssh-rsa", b64(str("ssh-rsa") + huge)))
        assertNull(KnownHostPortable.fromPortable("ssh-rsa", b64(str("ssh-rsa") + str(byteArrayOf(1, 0, 1)) + huge)))
        // Negative when read as a signed int too.
        assertNull(KnownHostPortable.fromPortable("ssh-ed25519", b64(str("ssh-ed25519") + u32(-1))))
        assertNull(KnownHostPortable.fromPortable("ssh-ed25519", b64(u32(0x7FFFFFFF) + ByteArray(8))))
    }

    @Test
    fun `the exact structure of each blob is enforced`() {
        val raw32 = ByteArray(32) { 5 }
        assertNull(KnownHostPortable.fromPortable("ssh-ed25519", b64(str("ssh-ed25519") + str(ByteArray(31)))))
        assertNull(KnownHostPortable.fromPortable("ssh-ed25519", b64(str("ssh-ed25519") + str(ByteArray(33)))))
        assertNull(KnownHostPortable.fromPortable("ssh-ed25519", b64(str("ssh-ed25519") + str(raw32) + byteArrayOf(0))))

        val point = byteArrayOf(4) + ByteArray(64) { 1 }
        val type = "ecdsa-sha2-nistp256"
        // wrong curve name for the type
        assertNull(KnownHostPortable.fromPortable(type, b64(str(type) + str("nistp384") + str(point))))
        // not an uncompressed point
        assertNull(KnownHostPortable.fromPortable(type, b64(str(type) + str("nistp256") + str(byteArrayOf(2) + ByteArray(64)))))
        // wrong point size
        assertNull(KnownHostPortable.fromPortable(type, b64(str(type) + str("nistp256") + str(point.copyOf(64)))))
        assertNull(KnownHostPortable.fromPortable(type, b64(str(type) + str("nistp256") + str(point + byteArrayOf(1)))))
        // trailing bytes
        assertNull(KnownHostPortable.fromPortable(type, b64(str(type) + str("nistp256") + str(point) + byteArrayOf(0))))

        val n = byteArrayOf(0) + ByteArray(256) { (it or 1).toByte() }
        val rsaType = "ssh-rsa"
        assertNull(KnownHostPortable.fromPortable(rsaType, b64(str(rsaType) + str(byteArrayOf(1, 0, 1)) + str(ByteArray(10) { 1 })))) // modulus too small
        assertNull(KnownHostPortable.fromPortable(rsaType, b64(str(rsaType) + str(ByteArray(0)) + str(n)))) // empty exponent
        assertNull(KnownHostPortable.fromPortable(rsaType, b64(str(rsaType) + str(byteArrayOf(1, 0, 1)) + str(ByteArray(257) { -1 })))) // negative modulus
        assertNull(KnownHostPortable.fromPortable(rsaType, b64(str(rsaType) + str(byteArrayOf(1, 0, 1)) + str(ByteArray(1100) { 1 })))) // modulus too large
        assertNull(KnownHostPortable.fromPortable(rsaType, b64(str(rsaType) + str(byteArrayOf(1, 0, 1)) + str(n) + byteArrayOf(0)))) // trailing
    }

    @Test
    fun `import refuses a blob over 8 KiB`() {
        val big = ByteArray(BackupLimits.MAX_PUBLIC_KEY_BLOB_BYTES + 1) { 1 }
        assertNull(KnownHostPortable.fromPortable("ssh-rsa", Base64.getEncoder().encodeToString(big)))
    }

    @Test
    fun `exported blobs stay under the limit`() {
        for (k in fixtureKnownHosts()) {
            assertTrue(Base64.getDecoder().decode(k.publicKey).size <= BackupLimits.MAX_PUBLIC_KEY_BLOB_BYTES)
        }
    }

    @Test
    fun `the text forms never print key material`() {
        val k = fixtureKnownHosts().first()
        val local = assertNotNull(KnownHostPortable.fromPortable(k.keyType, k.publicKey))
        assertEquals("LocalKey", local.toString())
        assertEquals("Portable", KnownHostPortable.Portable(k.keyType, k.publicKey).toString())
    }
}
