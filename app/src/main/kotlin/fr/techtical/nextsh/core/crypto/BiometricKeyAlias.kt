package fr.techtical.nextsh.core.crypto

/**
 * The one alias format of the biometric SSH keys the app generates in the Android Keystore:
 * `nextsh_bio_` followed by the id of the key, which is a random UUID.
 *
 * It matters because a Keystore alias coming from outside (a backup, a sync payload) can name any
 * entry of the app's Keystore, the vault master key `nextsh_vault_auth_key` included. An alias is
 * therefore only trusted, and only ever deleted, when it has exactly this shape.
 */
object BiometricKeyAlias {

    const val PREFIX = "nextsh_bio_"

    private val FORMAT =
        Regex("""nextsh_bio_[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}""")

    /** The alias to generate a biometric key under, for the SSH key whose id is [keyId]. */
    fun forKeyId(keyId: String): String = PREFIX + keyId

    /** True if [alias] has the shape of an alias generated by the app (full match, no extra text). */
    fun isValid(alias: String): Boolean = FORMAT.matches(alias)

    /**
     * The aliases of [aliases] that are biometric keys of the app, and only those: never the master key
     * of the vault (`nextsh_vault_auth_key`), a neighbouring alias or any other Keystore entry.
     */
    fun biometricAliasesOf(aliases: Iterable<String>): List<String> = aliases.filter { isValid(it) }

    /**
     * True if [alias] is exactly the alias the app generates for the key whose id is [keyId].
     * A key must never claim the alias of another key (or of any other Keystore entry): deleting
     * the key would then delete that entry.
     */
    fun matches(alias: String, keyId: String): Boolean = isValid(alias) && alias == forKeyId(keyId)
}
