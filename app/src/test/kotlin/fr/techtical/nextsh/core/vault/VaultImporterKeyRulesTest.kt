/**
 * The SSH keys of a restore ([VaultImporter] with the shared `BackupKeyRules`), with keys generated by the
 * test: a private key already on the device is never replaced, a public key only by the one derived from a
 * private key of the file and proven, a hardware key keeps everything. The backup is built and encrypted for
 * real; the repositories and the vault are mocked, the deriver is the real one.
 */
class VaultImporterKeyRulesTest {

    private val vaultManager = mockk<VaultManager>()
    private val sshKeyRepository = mockk<SshKeyRepository>()
    private val cryptoUtils = CryptoUtils()
    private val executor = Executors.newSingleThreadExecutor { Thread(it, "key-derive-test") }
    private val passphrase = "correct horse battery"

    /** Names of the threads the deriver ran on, and the passphrase arrays it was given. */
    private val derivedOn = mutableListOf<String>()
    private val passphrasesSeen = mutableListOf<CharArray?>()

    private lateinit var importer: VaultImporter

    private val recordingDeriver = PublicKeyDeriver { pem, pass ->
        derivedOn.add(Thread.currentThread().name)
        passphrasesSeen.add(pass)
        SshPublicKeyDeriver.derive(pem, pass)
    }

    @BeforeEach
    fun setUp() {
        every { vaultManager.isAuthRequired() } returns false
        justRun { vaultManager.storePrivateKey(any(), any()) }
        justRun { vaultManager.storeKeyPassphrase(any(), any()) }
        coEvery { sshKeyRepository.getById(any()) } returns null
        coEvery { sshKeyRepository.save(any()) } returns Unit
        importer = VaultImporter(
            vaultManager = vaultManager,
            sshKeyRepository = sshKeyRepository,
            hostRepository = mockk<HostRepository>(relaxed = true),
            tunnelRepository = mockk<TunnelRepository>(relaxed = true),
            backupRestoreStore = mockk<BackupRestoreStore>(relaxed = true),
            knownHostsVerifier = mockk<KnownHostsVerifier>(relaxed = true),
            settingsDataStore = mockk<SettingsDataStore>(relaxed = true),
            cryptoUtils = cryptoUtils,
            transactionRunner = FakeTransactionRunner(),
            publicKeyDeriver = recordingDeriver,
            derivationDispatcher = executor.asCoroutineDispatcher(),
        )
    }

    @AfterEach
    fun tearDown() {
        executor.shutdownNow()
    }

    private fun row(id: String, line: String, label: String = "Key $id") =
        SshKey(id = id, label = label, keyType = SshKeyType.ED25519, publicKey = line)

    private fun file(
        sshKeys: List<SshKey> = emptyList(),
        privateKeys: Map<String, String> = emptyMap(),
        keyPassphrases: Map<String, String> = emptyMap(),
    ): ByteArray {
        val document = BackupDocument(
            exportedAt = 1_000L,
            hosts = emptyList(),
            sshKeys = sshKeys,
            tunnels = emptyList(),
            credentials = emptyMap(),
            privateKeys = privateKeys,
            keyPassphrases = keyPassphrases,
        )
        val salt = cryptoUtils.generateSalt(32)
        val derived = cryptoUtils.deriveKeyFromPassphrase(passphrase.toCharArray(), salt)
        val sealed = cryptoUtils.encryptAesGcm(BackupCodec.encode(document).toByteArray(Charsets.UTF_8), derived)
        return BackupEnvelope.pack(salt, sealed)
    }

    private suspend fun restore(bytes: ByteArray): BackupImportReport =
        importer.import(bytes, passphrase.toCharArray()).getOrThrow()

    private fun savedKey(): SshKey {
        val saved = slot<SshKey>()
        coVerify(exactly = 1) { sshKeyRepository.save(capture(saved)) }
        return saved.captured
    }

    private fun blobKeyOf(key: SshKey): String =
        checkNotNull(SshPublicKeyLine.blobKey(key.publicKey)) { "the saved public key has no readable blob" }

    @Test
    fun `a private key already on the device is never replaced and the local public key stays`() = runTest {
        val local = TestSshKeys.ed25519("local")
        val offered = TestSshKeys.ed25519("offered")
        coEvery { sshKeyRepository.getById("k1") } returns row("k1", local.line, label = "Local label")
        every { vaultManager.getPrivateKey("k1") } returns local.pem

        val report = restore(
            file(
                sshKeys = listOf(row("k1", offered.line, label = "Label of the file")),
                privateKeys = mapOf("k1" to offered.pem),
            ),
        )

        verify(exactly = 0) { vaultManager.storePrivateKey(any(), any()) }
        val saved = savedKey()
        assertEquals(local.blobKey, blobKeyOf(saved))
        assertEquals("Label of the file", saved.label)
        assertEquals(1, report.localKeysKept)
        assertEquals(0, report.publicKeysRecomputed)
        assertEquals(0, report.privateKeys)
        assertTrue(BackupReportWarning.LOCAL_KEYS_KEPT in report.warnings())
        // The local key is not the file's one: nothing was derived.
        assertTrue(derivedOn.isEmpty())
    }

    @Test
    fun `the same private key on the device is written again and a wrong public line is replaced`() = runTest {
        val key = TestSshKeys.ed25519("mine")
        val thirdParty = TestSshKeys.ed25519("third-party")
        coEvery { sshKeyRepository.getById("k1") } returns row("k1", thirdParty.line)
        every { vaultManager.getPrivateKey("k1") } returns key.pem

        val report = restore(file(sshKeys = listOf(row("k1", thirdParty.line)), privateKeys = mapOf("k1" to key.pem)))

        assertEquals(key.blobKey, blobKeyOf(savedKey()))
        assertEquals(1, report.publicKeysRecomputed)
        assertEquals(0, report.localKeysKept)
    }

    @Test
    fun `a public key of a third party is replaced by the one derived from the private key of the file`() = runTest {
        val real = TestSshKeys.ed25519("real")
        val thirdParty = TestSshKeys.ed25519("third-party")

        val report = restore(
            file(sshKeys = listOf(row("k1", thirdParty.line)), privateKeys = mapOf("k1" to real.pem)),
        )

        val saved = savedKey()
        assertEquals(real.blobKey, blobKeyOf(saved))
        assertEquals("third-party", SshPublicKeyLine.comment(saved.publicKey))
        verify(exactly = 1) { vaultManager.storePrivateKey("k1", real.pem) }
        assertEquals(1, report.publicKeysRecomputed)
        assertEquals(0, report.localKeysKept)
        assertTrue(BackupReportWarning.PUBLIC_KEYS_RECOMPUTED in report.warnings())
    }

    @Test
    fun `a correct public line is kept as written and not counted`() = runTest {
        val key = TestSshKeys.ed25519("mine")

        val report = restore(file(sshKeys = listOf(row("k1", key.line)), privateKeys = mapOf("k1" to key.pem)))

        assertEquals(key.line, savedKey().publicKey)
        assertEquals(0, report.publicKeysRecomputed)
        assertEquals(0, report.localKeysKept)
    }

    @Test
    fun `a local key without a private key takes the derived public key of the file private key`() = runTest {
        val real = TestSshKeys.ed25519("real")
        val thirdParty = TestSshKeys.ed25519("third-party")
        coEvery { sshKeyRepository.getById("k1") } returns row("k1", thirdParty.line)
        every { vaultManager.getPrivateKey("k1") } returns null

        // The file has a private key and no row: the local row is repaired.
        val report = restore(file(privateKeys = mapOf("k1" to real.pem)))

        assertEquals(real.blobKey, blobKeyOf(savedKey()))
        verify(exactly = 1) { vaultManager.storePrivateKey("k1", real.pem) }
        assertEquals(1, report.publicKeysRecomputed)
    }

    @Test
    fun `an encrypted key with the right passphrase in the file is not derived at restore, its file line stays and the passphrase is written`() = runTest {
        val real = TestSshKeys.encryptedEd25519("file-pass")
        val thirdParty = TestSshKeys.ed25519("third-party")

        val report = restore(
            file(
                sshKeys = listOf(row("k1", thirdParty.line)),
                privateKeys = mapOf("k1" to real.pem),
                keyPassphrases = mapOf("k1" to "file-pass"),
            ),
        )

        assertEquals(thirdParty.line, savedKey().publicKey)
        verify(exactly = 1) { vaultManager.storePrivateKey("k1", real.pem) }
        verify(exactly = 1) { vaultManager.storeKeyPassphrase("k1", any()) }
        assertEquals(0, report.publicKeysRecomputed)
    }

    @Test
    fun `an encrypted key without its passphrase proves nothing and changes nothing`() = runTest {
        val real = TestSshKeys.encryptedEd25519("file-pass")
        val thirdParty = TestSshKeys.ed25519("third-party")

        val report = restore(file(sshKeys = listOf(row("k1", thirdParty.line)), privateKeys = mapOf("k1" to real.pem)))

        assertEquals(thirdParty.line, savedKey().publicKey)
        verify(exactly = 1) { vaultManager.storePrivateKey("k1", real.pem) }
        assertEquals(0, report.publicKeysRecomputed)
    }

    @Test
    fun `an encrypted key with a wrong passphrase proves nothing and changes nothing`() = runTest {
        val real = TestSshKeys.encryptedEd25519("file-pass")
        val thirdParty = TestSshKeys.ed25519("third-party")

        val report = restore(
            file(
                sshKeys = listOf(row("k1", thirdParty.line)),
                privateKeys = mapOf("k1" to real.pem),
                keyPassphrases = mapOf("k1" to "not-the-passphrase"),
            ),
        )

        assertEquals(thirdParty.line, savedKey().publicKey)
        assertEquals(0, report.publicKeysRecomputed)
    }

    @Test
    fun `the deriver never receives a passphrase and runs off the caller thread`() = runTest {
        val real = TestSshKeys.encryptedEd25519("file-pass")

        restore(
            file(
                sshKeys = listOf(row("k1", real.line)),
                privateKeys = mapOf("k1" to real.pem),
                keyPassphrases = mapOf("k1" to "file-pass"),
            ),
        )

        assertEquals(1, passphrasesSeen.size)
        assertNull(passphrasesSeen.single(), "no key derivation function may run at restore")
        assertEquals(listOf("key-derive-test"), derivedOn)
    }

    @Test
    fun `the same private key under two ids is derived once during one restore`() = runTest {
        val real = TestSshKeys.ed25519("mine")
        val thirdParty = TestSshKeys.ed25519("third-party")

        val report = restore(
            file(
                sshKeys = listOf(row("k1", thirdParty.line), row("k2", thirdParty.line)),
                privateKeys = mapOf("k1" to real.pem, "k2" to real.pem),
            ),
        )

        assertEquals(1, derivedOn.size, "one derivation for one private key text")
        assertEquals(2, report.publicKeysRecomputed)
        coVerify(exactly = 2) { sshKeyRepository.save(any()) }
    }

    @Test
    fun `two successive restores derive twice, the memo is not kept between them`() = runTest {
        val real = TestSshKeys.ed25519("mine")
        val bytes = file(sshKeys = listOf(row("k1", real.line)), privateKeys = mapOf("k1" to real.pem))

        restore(bytes)
        restore(bytes)

        assertEquals(2, derivedOn.size)
    }

    @Test
    fun `a local line without a private key in the vault is not paired with an unproven private key of the file`() = runTest {
        val local = TestSshKeys.ed25519("local")
        val encrypted = TestSshKeys.encryptedEd25519("file-pass")
        coEvery { sshKeyRepository.getById("k1") } returns row("k1", local.line)
        every { vaultManager.getPrivateKey("k1") } returns null

        val report = restore(file(sshKeys = listOf(row("k1", encrypted.line)), privateKeys = mapOf("k1" to encrypted.pem)))

        verify(exactly = 0) { vaultManager.storePrivateKey(any(), any()) }
        assertEquals(local.blobKey, blobKeyOf(savedKey()))
        assertEquals(0, report.publicKeysRecomputed)
    }

    @Test
    fun `a hardware key keeps its material, its private key is never written and it counts as kept`() = runTest {
        val alias = BiometricKeyAlias.forKeyId("k1")
        val hardware = SshKey(
            id = "k1",
            label = "Local biometric",
            keyType = SshKeyType.ECDSA_256,
            publicKey = "ecdsa-sha2-nistp256 AAAAHARDWARE nextsh-biometric",
            isBiometric = true,
            keystoreAlias = alias,
        )
        val offered = TestSshKeys.ed25519("offered")
        coEvery { sshKeyRepository.getById("k1") } returns hardware
        every { vaultManager.getPrivateKey("k1") } returns null

        val report = restore(
            file(sshKeys = listOf(row("k1", offered.line, label = "Label of the file")), privateKeys = mapOf("k1" to offered.pem)),
        )

        verify(exactly = 0) { vaultManager.storePrivateKey(any(), any()) }
        val saved = savedKey()
        assertEquals(hardware.publicKey, saved.publicKey)
        assertEquals(SshKeyType.ECDSA_256, saved.keyType)
        assertEquals(true, saved.isBiometric)
        assertEquals(alias, saved.keystoreAlias)
        assertEquals("Label of the file", saved.label)
        assertEquals(1, report.localKeysKept)
        assertEquals(0, report.publicKeysRecomputed)
        assertTrue(derivedOn.isEmpty())
    }

    @Test
    fun `a vault that cannot be read for an id counts as PRESENT, nothing is replaced and the restore goes on`() = runTest {
        val local = TestSshKeys.ed25519("local")
        val offered = TestSshKeys.ed25519("offered")
        coEvery { sshKeyRepository.getById("k1") } returns row("k1", local.line)
        every { vaultManager.getPrivateKey("k1") } throws IllegalStateException("vault read failed")

        val report = restore(file(sshKeys = listOf(row("k1", offered.line)), privateKeys = mapOf("k1" to offered.pem)))

        verify(exactly = 0) { vaultManager.storePrivateKey(any(), any()) }
        assertEquals(local.blobKey, blobKeyOf(savedKey()))
        assertEquals(1, report.localKeysKept)
    }

    @Test
    fun `a failing presence probe for a passphrase only file counts as PRESENT and writes no passphrase`() = runTest {
        val local = TestSshKeys.ed25519("local")
        coEvery { sshKeyRepository.getById("k1") } returns row("k1", local.line)
        every { vaultManager.hasPrivateKey("k1") } throws IllegalStateException("vault read failed")

        val report = restore(file(keyPassphrases = mapOf("k1" to "pp")))

        verify(exactly = 0) { vaultManager.storeKeyPassphrase(any(), any()) }
        assertEquals(0, report.keyPassphrases)
    }

    @Test
    fun `an expired vault window during the read still ends the restore with the re-authentication signal`() = runTest {
        val local = TestSshKeys.ed25519("local")
        val offered = TestSshKeys.ed25519("offered")
        coEvery { sshKeyRepository.getById("k1") } returns row("k1", local.line)
        every { vaultManager.getPrivateKey("k1") } throws VaultAuthExpiredException()

        var thrown: Throwable? = null
        try {
            restore(file(sshKeys = listOf(row("k1", offered.line)), privateKeys = mapOf("k1" to offered.pem)))
        } catch (e: VaultAuthExpiredException) {
            thrown = e
        }

        assertTrue(thrown is VaultAuthExpiredException)
        coVerify(exactly = 0) { sshKeyRepository.save(any()) }
    }

    @Test
    fun `a private key of the file without a row never overwrites a private key of the device`() = runTest {
        val local = TestSshKeys.ed25519("local")
        val offered = TestSshKeys.ed25519("offered")
        coEvery { sshKeyRepository.getById("k1") } returns row("k1", local.line)
        every { vaultManager.getPrivateKey("k1") } returns local.pem

        val report = restore(file(privateKeys = mapOf("k1" to offered.pem)))

        verify(exactly = 0) { vaultManager.storePrivateKey(any(), any()) }
        // The file brings another private key for a slot already taken: the device kept its own, counted.
        assertEquals(1, report.localKeysKept)
        assertEquals(0, report.privateKeys)
    }

    @Test
    fun `a passphrase of the file does not follow a private key that was not written`() = runTest {
        val local = TestSshKeys.ed25519("local")
        val offered = TestSshKeys.ed25519("offered")
        coEvery { sshKeyRepository.getById("k1") } returns row("k1", local.line)
        every { vaultManager.getPrivateKey("k1") } returns local.pem

        val report = restore(
            file(
                sshKeys = listOf(row("k1", offered.line)),
                privateKeys = mapOf("k1" to offered.pem),
                keyPassphrases = mapOf("k1" to "pp"),
            ),
        )

        verify(exactly = 0) { vaultManager.storeKeyPassphrase(any(), any()) }
        assertEquals(0, report.keyPassphrases)
    }

    @Test
    fun `a key that is new on the device with a key unreadable by the deriver is restored as it is`() = runTest {
        val report = restore(
            file(sshKeys = listOf(row("k1", "ssh-ed25519 AAAA c")), privateKeys = mapOf("k1" to "NOT A KEY")),
        )

        assertEquals("ssh-ed25519 AAAA c", savedKey().publicKey)
        verify(exactly = 1) { vaultManager.storePrivateKey("k1", "NOT A KEY") }
        assertEquals(0, report.publicKeysRecomputed)
        assertEquals(0, report.localKeysKept)
    }
}
