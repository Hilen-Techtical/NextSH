/**
 * The public key that "Copy" and "Download" put out ([VaultViewModel.publicKeyForExport]): the line of
 * the private key of the vault wins over the stored text, a wrong stored line is repaired, a key that
 * cannot be read is copied with a notice. Keys are generated by the test.
 */
@OptIn(ExperimentalCoroutinesApi::class)
class VaultViewModelPublicKeyTest {

    private val sshKeyRepository = mockk<SshKeyRepository>()
    private val vaultManager = mockk<VaultManager>()
    private val sshKeyManager = mockk<SshKeyManager>()
    private val keystoreManager = mockk<KeystoreManager>()
    private val testDispatcher = UnconfinedTestDispatcher()
    private lateinit var viewModel: VaultViewModel

    @BeforeEach
    fun setUp() {
        Dispatchers.setMain(testDispatcher)
        every { sshKeyRepository.observeAll() } returns flowOf(emptyList())
        coEvery { sshKeyRepository.update(any()) } returns Unit
        val hostRepository = mockk<HostRepository>()
        every { hostRepository.observeAll() } returns flowOf(emptyList())
        viewModel = VaultViewModel(
            sshKeyRepository = sshKeyRepository,
            hostRepository = hostRepository,
            vaultManager = vaultManager,
            sshKeyManager = sshKeyManager,
            keystoreManager = keystoreManager,
            biometricHelper = mockk<BiometricHelper>(),
            importSshKey = mockk<ImportSshKeyUseCase>(),
            generateSshKey = mockk<GenerateSshKeyUseCase>(),
            exportVaultUseCase = mockk<ExportVaultUseCase>(),
            importVaultUseCase = mockk<ImportVaultUseCase>(),
            documentDeleter = mockk<DocumentDeleter>(),
            keyUsageReader = mockk<KeyUsageReader>(),
            appLock = AppLock { 0L }.apply { unlock() },
            publicKeyDeriver = SshPublicKeyDeriver,
            derivationDispatcher = testDispatcher,
        )
    }

    @AfterEach
    fun tearDown() {
        viewModel.viewModelScope.cancel()
        Dispatchers.resetMain()
    }

    private fun softwareKey(line: String, id: String = "k1") =
        SshKey(id = id, label = "Key", keyType = SshKeyType.ED25519, publicKey = line)

    @Test
    fun `a stored line that matches the private key is copied as is without a notice`() = runTest {
        val real = TestSshKeys.ed25519("mine")
        every { vaultManager.getPrivateKey("k1") } returns real.pem
        every { vaultManager.getKeyPassphrase("k1") } returns null

        val export = viewModel.publicKeyForExport(softwareKey(real.line))

        assertEquals(real.line, export.line)
        assertNull(export.notice)
        coVerify(exactly = 0) { sshKeyRepository.update(any()) }
    }

    @Test
    fun `a stored line of another key is replaced by the derived one, the key is corrected and the notice says so`() = runTest {
        val real = TestSshKeys.ed25519("mine")
        val thirdParty = TestSshKeys.ed25519("third-party")
        every { vaultManager.getPrivateKey("k1") } returns real.pem
        every { vaultManager.getKeyPassphrase("k1") } returns null

        val export = viewModel.publicKeyForExport(softwareKey(thirdParty.line))

        assertEquals(real.blobKey, SshPublicKeyLine.blobKey(export.line!!))
        assertEquals(MessageRes(R.string.vault_message_pub_key_corrected), export.notice)
        val corrected = slot<SshKey>()
        coVerify(exactly = 1) { sshKeyRepository.update(capture(corrected)) }
        assertEquals(export.line, corrected.captured.publicKey)
    }

    @Test
    fun `an empty stored line is filled from the private key without a notice`() = runTest {
        val real = TestSshKeys.ed25519("mine")
        every { vaultManager.getPrivateKey("k1") } returns real.pem
        every { vaultManager.getKeyPassphrase("k1") } returns null

        val export = viewModel.publicKeyForExport(softwareKey(""))

        assertEquals(real.blobKey, SshPublicKeyLine.blobKey(export.line!!))
        assertNull(export.notice)
        coVerify(exactly = 1) { sshKeyRepository.update(any()) }
    }

    @Test
    fun `an encrypted key is read with its stored passphrase, which is wiped afterwards`() = runTest {
        val real = TestSshKeys.encryptedEd25519("vault-pass")
        val passphrase = "vault-pass".toCharArray()
        every { vaultManager.getPrivateKey("k1") } returns real.pem
        every { vaultManager.getKeyPassphrase("k1") } returns passphrase

        val export = viewModel.publicKeyForExport(softwareKey(real.line))

        assertEquals(real.line, export.line)
        assertNull(export.notice)
        assertTrue(passphrase.all { it == '\u0000' })
    }

    @Test
    fun `an encrypted key without a stored passphrase is copied as stored with the unverified notice`() = runTest {
        val real = TestSshKeys.encryptedEd25519("vault-pass")
        every { vaultManager.getPrivateKey("k1") } returns real.pem
        every { vaultManager.getKeyPassphrase("k1") } returns null

        val export = viewModel.publicKeyForExport(softwareKey(real.line))

        assertEquals(real.line, export.line)
        assertEquals(MessageRes(R.string.vault_message_pub_key_unverified), export.notice)
        coVerify(exactly = 0) { sshKeyRepository.update(any()) }
    }

    @Test
    fun `a key with no private key in the vault is copied as stored with the unverified notice`() = runTest {
        every { vaultManager.getPrivateKey("k1") } returns null

        val export = viewModel.publicKeyForExport(softwareKey("ssh-ed25519 AAAA stored"))

        assertEquals("ssh-ed25519 AAAA stored", export.line)
        assertEquals(MessageRes(R.string.vault_message_pub_key_unverified), export.notice)
    }

    @Test
    fun `a key with nothing stored and nothing to derive from has nothing to copy`() = runTest {
        every { vaultManager.getPrivateKey("k1") } returns null

        val export = viewModel.publicKeyForExport(softwareKey(""))

        assertNull(export.line)
        assertEquals(MessageRes(R.string.vault_message_pub_key_unavailable), export.notice)
    }

    @Test
    fun `a vault that cannot be read gives the stored line with the unverified notice`() = runTest {
        every { vaultManager.getPrivateKey("k1") } throws IllegalStateException("vault closed")

        val export = viewModel.publicKeyForExport(softwareKey("ssh-ed25519 AAAA stored"))

        assertEquals("ssh-ed25519 AAAA stored", export.line)
        assertEquals(MessageRes(R.string.vault_message_pub_key_unverified), export.notice)
    }

    @Test
    fun `a failing correction does not stop the copy`() = runTest {
        val real = TestSshKeys.ed25519("mine")
        val thirdParty = TestSshKeys.ed25519("third-party")
        every { vaultManager.getPrivateKey("k1") } returns real.pem
        every { vaultManager.getKeyPassphrase("k1") } returns null
        coEvery { sshKeyRepository.update(any()) } throws IllegalStateException("database closed")

        val export = viewModel.publicKeyForExport(softwareKey(thirdParty.line))

        assertEquals(real.blobKey, SshPublicKeyLine.blobKey(export.line!!))
    }

    @Test
    fun `a FIDO2 key gives its stored line, never reads the vault and has no notice`() = runTest {
        val key = SshKey(
            id = "k1",
            label = "Security key",
            keyType = SshKeyType.SK_ED25519,
            publicKey = "sk-ssh-ed25519@openssh.com AAAA stored",
            fido2CredentialId = "Y3JlZA==",
            fido2RpId = "ssh:",
        )

        val export = viewModel.publicKeyForExport(key)

        assertEquals("sk-ssh-ed25519@openssh.com AAAA stored", export.line)
        assertNull(export.notice)
        verify(exactly = 0) { vaultManager.getPrivateKey(any()) }
    }

    @Test
    fun `a biometric key gives the public key read from the Keystore`() = runTest {
        val alias = BiometricKeyAlias.forKeyId("k1")
        val keystorePublicKey = mockk<PublicKey>()
        every { keystoreManager.getBiometricPublicKey(alias) } returns keystorePublicKey
        every { sshKeyManager.formatKeystorePublicKeyOpenSsh(keystorePublicKey, "nextsh-biometric") } returns
            "ecdsa-sha2-nistp256 AAAAKEYSTORE nextsh-biometric"
        val key = SshKey(
            id = "k1",
            label = "Biometric",
            keyType = SshKeyType.ECDSA_256,
            publicKey = "ecdsa-sha2-nistp256 AAAASTORED nextsh-biometric",
            isBiometric = true,
            keystoreAlias = alias,
        )

        val export = viewModel.publicKeyForExport(key)

        assertEquals("ecdsa-sha2-nistp256 AAAAKEYSTORE nextsh-biometric", export.line)
        assertNull(export.notice)
        verify(exactly = 0) { vaultManager.getPrivateKey(any()) }
    }

    @Test
    fun `a biometric key that is not on this device copies nothing and says why`() = runTest {
        val alias = BiometricKeyAlias.forKeyId("k1")
        every { keystoreManager.getBiometricPublicKey(alias) } throws KeyStoreException("gone")
        val key = SshKey(
            id = "k1",
            label = "Biometric",
            keyType = SshKeyType.ECDSA_256,
            publicKey = "ecdsa-sha2-nistp256 AAAASTORED nextsh-biometric",
            isBiometric = true,
            keystoreAlias = alias,
        )

        val export = viewModel.publicKeyForExport(key)

        assertNull(export.line)
        assertEquals(MessageRes(R.string.vault_message_pub_key_biometric_missing), export.notice)
    }
}
